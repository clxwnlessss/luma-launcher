const { _electron: electron } = require('playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const os = require('node:os');
const path = require('node:path');
(async()=>{
  const directory=await fs.mkdtemp(path.join(os.tmpdir(),'luma-v3-ui-'));
  const env={...process.env,LUMA_TEST_MODE:'1',LUMA_TEST_DATA:directory};delete env.ELECTRON_RUN_AS_NODE;
  let app;const errors=[];
  try{
    app=await electron.launch({args:[path.join(__dirname,'..')],env});
    const page=await app.firstWindow();page.on('pageerror',e=>errors.push(e.message));
    await page.locator('.client-detected').filter({hasText:'Клиент найден'}).waitFor();
    assert.equal(await page.locator('html').getAttribute('lang'),'ru');
    await page.locator('[data-action="launch-client"]').click();
    await page.locator('.toast').filter({hasText:'Запрос передан Roblox'}).waitFor();
    await page.locator('[data-action="check-updates"]').click();
    await page.getByText('Установлена актуальная сборка',{exact:true}).waitFor();
    await page.screenshot({path:'preview-luma-ru.png',animations:'disabled',scale:'css'});
    await page.locator('#language').selectOption('en');
    await page.locator('html[lang="en"]').waitFor();
    await page.getByRole('button',{name:'Launch Roblox',exact:true}).waitFor();
    await page.screenshot({path:'preview-luma-en.png',animations:'disabled',scale:'css'});
    await page.locator('[data-view="appearance"]').click();
    await page.locator('[data-setting="motion"]').click();
    await page.locator('body[data-motion="off"]').waitFor();
    await page.locator('[data-accent="blue"]').click();
    await page.locator('body[data-accent="blue"]').waitFor();
    await page.locator('[data-view="behavior"]').click();
    await page.locator('[data-setting="minimizeAfterLaunch"]').click();
    await page.locator('[data-setting="minimizeAfterLaunch"][aria-checked="true"]').waitFor();
    await page.locator('[data-setting="closeToTray"]').click();
    await page.locator('[data-setting="closeToTray"][aria-checked="true"]').waitFor();
    await page.locator('[data-setting="closeToTray"]').click();
    await page.locator('[data-setting="closeToTray"][aria-checked="false"]').waitFor();
    await page.locator('[data-view="diagnostics"]').click();
    await page.locator('[data-action="export-report"]').click();
    await page.locator('.toast').filter({hasText:'Report saved.'}).waitFor();
    await page.locator('[data-view="library"]').click();
    await page.locator('#add-top').click();
    await page.locator('#game-name').fill('Test world <b>safe</b>');
    await page.locator('#game-link').fill('https://evil.test/games/123');
    await page.locator('#save-game').click();
    await page.locator('#form-error').filter({hasText:'Enter a numeric Place ID'}).waitFor();
    await page.locator('#game-link').fill('123');await page.locator('#save-game').click();
    await page.locator('.game-card').waitFor();
    assert.equal(await page.locator('.card-title').textContent(),'Test world <b>safe</b>');
    assert.equal(await page.locator('.card-title b').count(),0);
    await page.locator('[data-favorite="123"]').click();
    await page.locator('[data-favorite="123"][aria-pressed="true"]').waitFor();
    await page.locator('[data-filter="favorites"]').click();
    assert.equal(await page.locator('.game-card').count(),1);
    await page.locator('#search').fill('no match');assert.equal(await page.locator('.game-card').count(),0);
    await page.locator('#search').fill('');await page.locator('[data-launch="123"]').click();
    await page.locator('.toast').filter({hasText:'Launch request sent to Roblox.'}).waitFor();
    await page.locator('[data-view="history"]').click();await page.locator('.history-row').waitFor();
    await app.close();
    app=await electron.launch({args:[path.join(__dirname,'..')],env});
    const next=await app.firstWindow();next.on('pageerror',e=>errors.push(e.message));
    await next.locator('html[lang="en"]').waitFor();
    await next.locator('body[data-accent="blue"][data-motion="off"]').waitFor();
    await next.locator('[data-view="behavior"]').click();
    await next.locator('[data-setting="minimizeAfterLaunch"][aria-checked="true"]').waitFor();
    await next.locator('[data-view="library"]').click();await next.locator('.game-card').waitFor();
    await next.locator('[data-remove="123"]').click();await next.locator('#confirm-cancel').click();
    assert.equal(await next.locator('.game-card').count(),1);
    await next.locator('[data-remove="123"]').click();await next.locator('#confirm-accept').click();
    await next.locator('.empty-state').waitFor();
    await next.locator('#language').selectOption('ru');await next.locator('html[lang="ru"]').waitFor();
    await next.locator('#add-top').click();await next.locator('#game-name').fill('Тест');await next.locator('#game-link').fill('invalid');await next.locator('#save-game').click();
    await next.locator('#form-error').filter({hasText:'Введи числовой Place ID'}).waitFor();await next.keyboard.press('Escape');
    for(const language of ['ru','en']){
      await next.locator('#language').selectOption(language);await next.locator(`html[lang="${language}"]`).waitFor();
      for(const view of ['client','appearance','behavior','diagnostics','library','history','about']){
        await next.locator(`[data-view="${view}"]`).click();
        assert.equal(await next.locator('#content').innerText().then(text=>/[іїєґ]/iu.test(text)),false,`${language}/${view}`);
        assert.equal(await next.locator('#content').innerText().then(text=>text.includes(language==='ru'?'Не удалось выполнить действие':'The action could not be completed')),false,`${language}/${view} missing localization`);
      }
    }
    await next.locator('[data-view="client"]').click();await next.locator('[data-action="install-client"]').first().click();
    await next.locator('#confirm-accept').click();await next.getByText('Installer opened. Finish installation, then click Scan again.',{exact:false}).first().waitFor();
    await app.evaluate(({BrowserWindow})=>BrowserWindow.getAllWindows()[0].setSize(940,680));
    await next.screenshot({path:'preview-luma-small.png',animations:'disabled',scale:'css'});
    assert.equal(await next.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
    assert.equal(await next.evaluate(()=>typeof window.require),'undefined');
    assert.deepEqual(errors,[]);
    console.log('UI passed: RU/EN pages and errors, language persistence, client launch/version/installer IPC, settings/tray, diagnostics, library/history/favorites/search/deletion, XSS escaping, responsive layout. External launches/downloads mocked.');
  }finally{if(app)await app.close().catch(()=>{});await fs.rm(directory,{recursive:true,force:true});}
})().catch(error=>{console.error(error);process.exitCode=1;});
